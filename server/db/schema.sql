-- AutoPulse: структура бази даних. Повторний запуск безпечний.
CREATE TABLE IF NOT EXISTS products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(64) NOT NULL UNIQUE,
  title VARCHAR(150) NOT NULL,
  brand VARCHAR(60) NOT NULL,
  category VARCHAR(60) NOT NULL,
  description TEXT NOT NULL,
  price_uah INTEGER NOT NULL CHECK (price_uah >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  image_key VARCHAR(32) NOT NULL DEFAULT 'oil',
  position INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  reference VARCHAR(24) NOT NULL UNIQUE,
  product_id INTEGER NOT NULL REFERENCES products(id),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 20),
  client_name VARCHAR(80) NOT NULL,
  client_phone VARCHAR(20) NOT NULL,
  city VARCHAR(60) NOT NULL,
  delivery VARCHAR(20) NOT NULL CHECK (delivery IN ('nova_poshta', 'ukrposhta', 'pickup')),
  vin VARCHAR(17) NOT NULL DEFAULT '',
  comment VARCHAR(500) NOT NULL DEFAULT '',
  total_uah INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'confirmed', 'cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS orders_created_idx ON orders (created_at);
